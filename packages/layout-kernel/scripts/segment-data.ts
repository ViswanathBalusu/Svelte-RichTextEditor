/**
 * Writes `crates/layout-kernel/src/segment_data.rs`: the two small tables that the kernel's line
 * breaking (WASM-007) needs beside the `unicode-linebreak` crate, which has neither:
 *
 * - the opening punctuation with East Asian Width F, W or H (rule LB30 of UAX #14 lets a line break
 *   before these after a letter or a number);
 * - the unassigned code points that are Extended_Pictographic (rule LB30b keeps an emoji modifier
 *   with them).
 *
 *   node scripts/segment-data.ts [<.../tlpkg/tlperl/lib/unicore>]
 *
 * The source is the Unicode Character Database as Perl ships it (`To/Lb.pl`, `To/Ea.pl`, `To/Gc.pl`,
 * `lib/ExtPict/Y.pl`), which TeX Live carries; `bidi-data.ts` reads the same database. Its version
 * is read from the files and written into the output, and a native test of the crate fails when it
 * is not the version `unicode-linebreak` implements. Upgrading Unicode is this script run on the
 * database of the new version, then the conformance and golden tests of the kernel.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readTable } from './bidi-data.ts';

const LAST = 0x10ffff;

/** One value for each code point, from a `To/*.pl` table and the value of the points it omits. */
function property(path: string, missing: string): { version: string; of: string[] } {
  const { version, rows } = readTable(path);
  const of = new Array<string>(LAST + 1).fill(missing);
  for (const [start, end, value] of rows) for (let c = start; c <= end; c++) of[c] = value;
  return { version, of };
}

/**
 * A Perl inversion list (`lib/<property>/Y.pl`): `V<count>`, then that many decimal code points,
 * which start a range that has the property and a range that has not, in turn.
 */
export function readInversionList(path: string): { version: string; has: Uint8Array } {
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const version = /Version (\d+\.\d+\.\d+)/.exec(text)?.[1] ?? 'unknown';
  const body = text.slice(text.indexOf("<<'END';\n") + 9, text.lastIndexOf('END'));
  const lines = body.split('\n').filter((l) => l.trim() !== '');
  const count = Number(/^V(\d+)$/.exec(lines[0] ?? '')?.[1] ?? Number.NaN);
  const points = lines.slice(1).map((l) => Number.parseInt(l, 10));
  if (Number.isNaN(count) || points.length !== count || points.some((p) => Number.isNaN(p)))
    throw new Error(`${path} is not an inversion list`);
  const has = new Uint8Array(LAST + 1);
  for (let i = 0; i < points.length; i += 2)
    has.fill(1, points[i], Math.min(points[i + 1] ?? LAST + 1, LAST + 1));
  return { version, has };
}

/** The ranges `[first, last]` of the code points for which `test` holds, ascending. */
function ranges(test: (codePoint: number) => boolean): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (let c = 0; c <= LAST; c++) {
    if (!test(c)) continue;
    const last = out.at(-1);
    if (last && last[1] + 1 === c) last[1] = c;
    else out.push([c, c]);
  }
  return out;
}

export function generate(unicore: string): string {
  const lb = property(resolve(unicore, 'To/Lb.pl'), 'XX');
  const ea = property(resolve(unicore, 'To/Ea.pl'), 'N');
  const gc = property(resolve(unicore, 'To/Gc.pl'), 'Cn');
  const pictographic = readInversionList(resolve(unicore, 'lib/ExtPict/Y.pl'));
  for (const v of [ea.version, gc.version, pictographic.version])
    if (v !== lb.version) throw new Error('the tables are of different Unicode versions');

  const wide = (c: number): boolean => ea.of[c] === 'F' || ea.of[c] === 'W' || ea.of[c] === 'H';
  const open = ranges((c) => lb.of[c] === 'OP' && wide(c));
  // LB30 has a second half for closing parentheses. No CP has such a width in Unicode 15.0.0, and
  // the kernel has no code for one, so a version that gains one must be looked at by a person.
  const close = ranges((c) => lb.of[c] === 'CP' && wide(c));
  if (close.length > 0)
    throw new Error(
      `a closing parenthesis (CP) has East Asian Width F, W or H in Unicode ${lb.version}: ` +
        'segment.rs implements only the opening half of LB30',
    );
  const reserved = ranges((c) => pictographic.has[c] === 1 && gc.of[c] === 'Cn');
  if (open.length === 0 || reserved.length === 0) throw new Error('a table came out empty');

  const hex = (n: number): string => `0x${n.toString(16).toUpperCase()}`;
  const table = (rows: Array<[number, number]>): string =>
    rows.map(([s, e]) => `    (${hex(s)}, ${hex(e)}),\n`).join('');
  let out = `//! Generated by packages/layout-kernel/scripts/segment-data.ts from the Unicode Character Database\n`;
  out += `//! ${lb.version} (Line_Break, East_Asian_Width, General_Category, Extended_Pictographic). Do not edit\n`;
  out += `//! by hand.\n\n`;
  out += `/// The Unicode version of the tables.\npub const UNICODE_VERSION: &str = "${lb.version}";\n\n`;
  out += `/// The opening punctuation (Line_Break OP) with East_Asian_Width F, W or H, as ranges\n`;
  out += `/// \`(first, last)\`, ascending (UAX #14, rule LB30).\n`;
  out += `pub const EAST_ASIAN_OPEN: &[(u32, u32)] = &[\n${table(open)}];\n\n`;
  out += `/// The unassigned code points (General_Category Cn) that are Extended_Pictographic, as ranges\n`;
  out += `/// \`(first, last)\`, ascending (UAX #14, rule LB30b).\n`;
  out += `pub const EXTPICT_UNASSIGNED: &[(u32, u32)] = &[\n${table(reserved)}];\n`;
  return out;
}

if (import.meta.main) {
  const unicore = resolve(process.argv[2] ?? 'E:/texlive/2025/tlpkg/tlperl/lib/unicore');
  const file = resolve(import.meta.dirname, '../../../crates/layout-kernel/src/segment_data.rs');
  writeFileSync(file, generate(unicore));
  console.log('written', file);
}
