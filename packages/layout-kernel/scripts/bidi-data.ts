/**
 * Writes `crates/layout-kernel/src/bidi_data.rs`: the Bidi_Class of every code point and the paired
 * brackets (Bidi_Paired_Bracket), for the kernel's UAX #9 (WASM-015).
 *
 *   node scripts/bidi-data.ts [<.../tlpkg/tlperl/lib/unicore>]
 *
 * The source is the Unicode Character Database as Perl ships it (`To/Bc.pl`, `To/Bpb.pl`,
 * `To/Bpt.pl`), which TeX Live carries; its version is read from the files and written into the
 * output. Upgrading Unicode is this script run on a newer database, then the golden tests of the
 * kernel (a deliberate change, WASM-007's rule for Unicode data applies here as well).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** The classes in the order of the crate's `Class` enum. */
export const CLASSES = [
  'L',
  'R',
  'AL',
  'EN',
  'ES',
  'ET',
  'AN',
  'CS',
  'NSM',
  'BN',
  'B',
  'S',
  'WS',
  'ON',
  'LRE',
  'LRO',
  'RLE',
  'RLO',
  'PDF',
  'LRI',
  'RLI',
  'FSI',
  'PDI',
] as const;

/** The body of a Perl `To/*.pl` table: lines of `start<TAB>end<TAB>value`, and the Unicode version. */
export function readTable(path: string): {
  version: string;
  rows: Array<[number, number, string]>;
} {
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const version = /Version (\d+\.\d+\.\d+)/.exec(text)?.[1] ?? 'unknown';
  const body = text.slice(text.indexOf("<<'END';\n") + 9, text.lastIndexOf('END'));
  const rows: Array<[number, number, string]> = [];
  for (const line of body.split('\n')) {
    if (line.trim() === '') continue;
    const [a, b, v] = line.split('\t');
    const start = Number.parseInt(a!, 16);
    rows.push([start, b ? Number.parseInt(b, 16) : start, v ?? '']);
  }
  return { version, rows };
}

export function generate(unicore: string): string {
  const bc = readTable(resolve(unicore, 'To/Bc.pl'));
  const bpb = readTable(resolve(unicore, 'To/Bpb.pl'));
  const bpt = readTable(resolve(unicore, 'To/Bpt.pl'));
  if (bc.version !== bpb.version || bc.version !== bpt.version)
    throw new Error('the tables are of different Unicode versions');
  const code = (name: string): number => {
    const i = (CLASSES as readonly string[]).indexOf(name);
    if (i === -1) throw new Error(`unknown bidi class ${name}`);
    return i;
  };
  // Merge adjacent ranges of one class; classes the table leaves out are L (its `missing` value).
  const ranges: Array<[number, number, number]> = [];
  for (const [s, e, v] of bc.rows) {
    const c = code(v);
    const last = ranges.at(-1);
    if (last && last[2] === c && last[1] + 1 === s) last[1] = e;
    else ranges.push([s, e, c]);
  }
  const kind = new Map(bpt.rows.map(([s, , v]) => [s, v] as const));
  const brackets = bpb.rows.map(([s, , v]) => {
    const t = kind.get(s);
    if (t !== 'O' && t !== 'C') throw new Error(`U+${s.toString(16)} is neither open nor close`);
    return [s, Number.parseInt(v, 16), t === 'O' ? 1 : 0] as const;
  });
  const hex = (n: number): string => `0x${n.toString(16)}`;
  let out = `//! Generated by packages/layout-kernel/scripts/bidi-data.ts from the Unicode Character Database\n`;
  out += `//! ${bc.version} (Bidi_Class, Bidi_Paired_Bracket, Bidi_Paired_Bracket_Type). Do not edit by hand.\n\n`;
  out += `/// The Unicode version of the tables.\npub const UNICODE_VERSION: &str = "${bc.version}";\n\n`;
  out += `/// Bidi_Class ranges \`(first, last, class)\`, ascending; a code point in none is \`L\`.\n`;
  out += `/// Class numbers follow the order of \`Class\` in \`bidi.rs\`.\n`;
  out += `pub const CLASS_RANGES: &[(u32, u32, u8)] = &[\n`;
  for (const [s, e, c] of ranges) out += `    (${hex(s)}, ${hex(e)}, ${c}),\n`;
  out += `];\n\n`;
  out += `/// Paired brackets \`(bracket, its pair, is_open)\`, ascending.\n`;
  out += `pub const BRACKETS: &[(u32, u32, bool)] = &[\n`;
  for (const [s, p, o] of brackets) out += `    (${hex(s)}, ${hex(p)}, ${o === 1}),\n`;
  out += `];\n`;
  return out;
}

if (import.meta.main) {
  const unicore = resolve(process.argv[2] ?? 'E:/texlive/2025/tlpkg/tlperl/lib/unicore');
  const file = resolve(import.meta.dirname, '../../../crates/layout-kernel/src/bidi_data.rs');
  writeFileSync(file, generate(unicore));
  console.log('written', file);
}
