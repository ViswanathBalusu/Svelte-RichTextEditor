/**
 * Generates the TypeScript types of CDM documents from the definition (CDM-006). The output has no
 * ProseMirror import, so a consumer needs only these types and a JSON parser.
 */
import { NODE_MARK_HOSTS } from '../definition/cdm1.ts';
import type {
  CdmDefinition,
  Grammar,
  MarkDef,
  NodeDef,
  ProjectionNodeDef,
} from '../definition/grammar.ts';
import { allowedChildren } from './content-expr.ts';

const pascal = (s: string): string =>
  s
    .replace(/(^|_)([a-z])/g, (_, __, c: string) => c.toUpperCase())
    .replace(/^./, (c) => c.toUpperCase());

function tsType(g: Grammar): string {
  let t: string;
  switch (g.kind) {
    case 'string':
    case 'ref':
      t = 'string';
      break;
    case 'integer':
      t = 'number';
      break;
    case 'boolean':
      t = 'boolean';
      break;
    case 'enum':
      t = g.values.map((v) => JSON.stringify(v)).join(' | ');
      break;
    case 'object': {
      const req = new Set(g.required ?? []);
      const members = Object.entries(g.properties).map(
        ([k, v]) => `${k}${req.has(k) ? '' : '?'}: ${tsType(v)}`,
      );
      t = `{ ${members.join('; ')} }`;
      break;
    }
    case 'array': {
      const inner = tsType(g.items);
      t = /[|&{]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
      break;
    }
    case 'json':
      t = g.objectOnly ? '{ [key: string]: JsonValue }' : 'JsonValue';
      break;
    case 'elementTree':
      t = g.noRef ? 'PreservedElementBody' : 'PreservedElementBody | PreservedTreeRef';
      break;
  }
  return g.nullable ? `${t} | null` : t;
}

const quoteKey = (k: string): string => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function attrsInterface(name: string, def: NodeDef | MarkDef | ProjectionNodeDef): string {
  const lines = Object.entries(def.attrs).map(([k, a]) => {
    const doc = a.doc.replace(/\*\//g, '* /');
    const t = tsType(a.grammar);
    // Null where the default is null: ProseMirror creates the node with it (03 §9).
    const withNull = a.default === null ? (t.endsWith('| null') ? t : `${t} | null`) : t;
    return `  /** ${doc} Default: ${JSON.stringify(a.default)}. */\n  ${quoteKey(k)}?: ${withNull};`;
  });
  return `export interface ${name} {\n${lines.join('\n')}\n}`;
}

export function generateTypes(def: CdmDefinition): string {
  const out: string[] = [];
  out.push(
    `// GENERATED by packages/model/scripts/generate.ts from src/definition. Do not edit by hand.`,
    `// CDM version ${def.cdm} (${def.status}). See docs/spec/03-document-model.md.`,
    `/* eslint-disable */`,
    ``,
    `export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };`,
    ``,
    `export type CdmFeature = ${def.features.map((f) => JSON.stringify(f.name)).join(' | ')};`,
    ``,
    `/** Preserved attributes and child elements of an original element, in Clark notation (ADR 0017). */`,
    `export interface PreservedElementBody {`,
    `  attrs?: { [clarkName: string]: string };`,
    `  children?: Array<PreservedElement | { text: string }>;`,
    `}`,
    `export interface PreservedElement extends PreservedElementBody {`,
    `  name: string;`,
    `}`,
    `/** A reference to the shared tree of a preserved_def (spike S11). */`,
    `export interface PreservedTreeRef {`,
    `  ref: string;`,
    `}`,
    ``,
  );
  for (const m of def.marks) {
    const n = pascal(m.name);
    out.push(attrsInterface(`${n}MarkAttrs`, m), '');
    out.push(`/** ${m.doc}${m.feature ? ` Feature \`${m.feature}\`.` : ''} (${m.spec}) */`);
    out.push(
      `export interface ${n}Mark {\n  type: ${JSON.stringify(m.name)};\n  attrs?: ${n}MarkAttrs;\n}`,
      '',
    );
  }
  out.push(
    `export type CdmMark = ${def.marks.map((m) => `${pascal(m.name)}Mark`).join(' | ')};`,
    '',
  );
  out.push(`export type SuggestionNodeMark = InsMark | DelMark | FmtMark;`, '');

  for (const n of def.nodes) {
    const name = pascal(n.name);
    const doc = `/** ${n.doc}${n.feature ? ` Feature \`${n.feature}\`.` : ''} (${n.spec}) */`;
    if (n.name === 'text') {
      out.push(
        doc,
        `export interface TextNode {\n  type: "text";\n  text: string;\n  marks?: CdmMark[];\n}`,
        '',
      );
      continue;
    }
    const members: string[] = [`  type: ${JSON.stringify(n.name)};`];
    if (Object.keys(n.attrs).length) {
      out.push(attrsInterface(`${name}Attrs`, n), '');
      members.push(`  attrs?: ${name}Attrs;`);
    }
    if (n.content) {
      const children = allowedChildren(def, n.content).map((c) => `${pascal(c)}Node`);
      members.push(`  content?: Array<${children.join(' | ')}>;`);
    }
    if (NODE_MARK_HOSTS.includes(n.name)) members.push('  marks?: SuggestionNodeMark[];');
    else if (n.inline) members.push('  marks?: CdmMark[];');
    out.push(doc, `export interface ${name}Node {\n${members.join('\n')}\n}`, '');
  }
  out.push(
    `export type CdmNode = ${def.nodes.map((n) => `${pascal(n.name)}Node`).join(' | ')};`,
    '',
  );
  const block = def.nodes
    .filter((n) => (n.group ?? '').split(' ').includes('block'))
    .map((n) => `${pascal(n.name)}Node`);
  const inline = def.nodes
    .filter((n) => (n.group ?? '').split(' ').includes('inline'))
    .map((n) => `${pascal(n.name)}Node`);
  out.push(
    `export type BlockNode = ${block.join(' | ')};`,
    `export type InlineNode = ${inline.join(' | ')};`,
    '',
  );
  out.push(
    `/** A CDM document as stored and transferred (03 §2). */`,
    `export interface CdmEnvelope {`,
    `  cdm: ${def.cdm};`,
    `  requires: CdmFeature[];`,
    `  doc: ${pascal(def.topNode)}Node;`,
    `}`,
    '',
  );
  const projection = def.projection ?? [];
  if (projection.length) {
    out.push(
      `// Projections (ADR 0019): nodes that only a reader's projection contains, never a stored document.`,
      '',
    );
    for (const p of projection) {
      const name = pascal(p.name);
      out.push(attrsInterface(`${name}Attrs`, p), '');
      out.push(
        `/** ${p.doc} In the content of ${p.allowedIn.map((h) => `\`${h}\``).join(', ')} in a projection. (${p.spec}) */`,
        `export interface ${name}Node {\n  type: ${JSON.stringify(p.name)};\n  attrs?: ${name}Attrs;\n}`,
        '',
      );
    }
    out.push(
      `export type ProjectionOnlyNode = ${projection.map((p) => `${pascal(p.name)}Node`).join(' | ')};`,
      '',
    );
  }
  return out.join('\n');
}
