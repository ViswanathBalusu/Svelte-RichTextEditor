/**
 * The parity profile (13 §2; UX-001; ADR 0014): every capability in exactly one tier, said as what
 * a user can do, with the stories that deliver it. This file is the source; `pnpm --filter
 * @docedit/ui generate` writes the published artifact to `spec/parity/` (never edited by hand), and
 * `test/parity.test.ts` fails when the artifact is stale or a check below fails.
 *
 * Rules (UX-001):
 * - `items` quote 13 §2 verbatim; every item of 13 §2 is covered, in its own tier only. Rows that
 *   13 §2 does not list (basic editing, sharing, keyboard shortcuts, views, regions and
 *   permissions) cite their own section in `spec`.
 * - `can` says what a user can do, in this product's words: no look, arrangement or name of
 *   another product (13 §1). "Word file" names a format, which 13 §1 allows.
 * - Phases are not written here: they come from the delivering stories.
 * - A non-goal has no delivering story. Changing the set of non-goals needs an owner decision,
 *   recorded in PRODUCT.md and 13 §2 in the same change set, and `NON_GOAL_DECISION` updated.
 */

export type Tier = 'built-in' | 'ports-and-extensions' | 'non-goal';

export interface ProfileRow {
  readonly id: string;
  readonly tier: Tier;
  /** What a user can do (or, for a non-goal, what they cannot). */
  readonly can: string;
  /** The items of 13 §2 this row covers, verbatim; empty for a row from another section. */
  readonly items: readonly string[];
  readonly spec: string;
  /** Stories that deliver the capability. */
  readonly stories: readonly string[];
  /** What is missing: no story, or part of the capability without one. */
  readonly gap?: string;
}

