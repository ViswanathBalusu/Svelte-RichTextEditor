/**
 * The shared corpus (FND-006): every document is valid CDM, the generator is deterministic, the
 * manifest matches the files, the version moves with the output, and the corpus covers the
 * constructs FND-006 lists.
 */
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { documentHash, sha256HexBytes, type JsonEnvelope } from '@docedit/model';
import { validate } from '@docedit/model/validate';
import {
  corpusLabel,
  corpusStamp,
  corpusVersion,
  documentEntry,
  documentFile,
  documentNames,
  loadDocument,
  manifest,
  serializeDocument,
  type CorpusStamp,
} from '../src/index.ts';
import {
  CORPUS_HISTORY,
  CURRENT,
  fingerprintOf,
  generateCorpus,
  RECIPES,
  type GeneratedCorpus,
} from '../src/generate/index.ts';

declare module 'vitest' {
  interface TaskMeta {
    corpus?: CorpusStamp;
  }
}

const out = new URL('../out/', import.meta.url);
const onDisk = (path: string): boolean => existsSync(new URL(path, out));
const read = async (path: string): Promise<Uint8Array> =>
  new Uint8Array(await readFile(new URL(path, out)));

let fresh: GeneratedCorpus;
let generationMs = 0;

beforeAll(async () => {
  const t = performance.now();
  fresh = await generateCorpus();
  generationMs = performance.now() - t;
});

// Every result of this file records the corpus it ran against (FND-006), as the README asks of
// every test that uses the corpus.
beforeEach(({ task }) => {
  task.meta.corpus = corpusStamp();
});

/** The first offset where two byte arrays differ, or -1 when they are equal. (toEqual is slow on megabytes.) */
function firstDifference(a: Uint8Array, b: Uint8Array): number {
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) if (a[i] !== b[i]) return i;
  return a.length === b.length ? -1 : n;
}

function freshFile(path: string): Uint8Array {
  const f = fresh.files.find((x) => x.path === path);
  if (!f) throw new Error(`the generator did not produce ${path}`);
  return f.bytes;
}

/** The document as a test uses it: the file when it exists, otherwise the generated bytes. */
async function documentJson(name: string): Promise<JsonEnvelope> {
  const path = documentEntry(name).file;
  const bytes = onDisk(path) ? await read(path) : freshFile(path);
  return JSON.parse(new TextDecoder().decode(bytes)) as JsonEnvelope;
}

describe('the corpus documents (FND-006)', () => {
  it('gives every test result the corpus version and fingerprint to record', async ({
    task,
    annotate,
  }) => {
    expect(task.meta.corpus).toEqual({
      corpus: 'docedit-corpus',
      version: corpusVersion,
      fingerprint: manifest.fingerprint,
    });
    const annotation = await annotate(corpusLabel(), 'corpus');
    expect(annotation.message).toBe(
      `docedit-corpus ${corpusVersion} (${manifest.fingerprint.slice(0, 8)})`,
    );
  });

  it.each(RECIPES.map((r) => r.name))('%s passes validate() with no violations', async (name) => {
    const env = await documentJson(name);
    const result = validate(env, {
      attachedAssets: new Set(documentEntry(name).assets),
      retiredRegionIds: new Set(),
    });
    expect(result.violations).toEqual([]);
    expect(result.valid).toBe(true);
    // Attached assets (I4) and retired region identifiers (I3) were given, so both were checked.
    expect(result.notChecked.filter((n) => /^I[34] /.test(n))).toEqual([]);
  });

  it('holds documents of about 1, 20, 100, 300 and 1,000 pages, with estimated page counts', () => {
    const sizes = manifest.documents.filter((d) => d.name.startsWith('pages-'));
    expect(sizes.map((d) => d.pages.target)).toEqual([1, 20, 100, 300, 1000]);
    for (const d of manifest.documents) {
      // Estimated until spike S4 measures a count (src/generate/measured.ts).
      if (d.pages.status === 'estimated') expect(d.pages.measured).toBeNull();
      else expect(d.pages.measuredBy).toBeTruthy();
      // "About": one page exactly for the one-page documents, otherwise within 15 percent.
      if (d.pages.target === 1) expect(d.pages.estimated, d.name).toBe(1);
      else
        expect(Math.abs(d.pages.estimated - d.pages.target), d.name).toBeLessThanOrEqual(
          Math.ceil(d.pages.target * 0.15),
        );
    }
    expect(manifest.pageEstimate.status).toBe('estimated');
  });

  it('keeps every document within the canonical size limit of invariant I7', () => {
    for (const d of manifest.documents)
      expect(d.canonicalBytes).toBeLessThanOrEqual(16 * 1024 * 1024);
  });

  it('records the licence and provenance of every text and image', () => {
    const sources = new Set(manifest.sources.map((s) => s.id));
    for (const s of manifest.sources) {
      expect(s.licence).toBe(manifest.licence.id);
      expect(s.provenance).toMatch(/original/i);
    }
    for (const d of manifest.documents)
      for (const s of d.sources) expect(sources.has(s)).toBe(true);
    for (const a of manifest.assets) {
      expect(a.licence).toBe(manifest.licence.id);
      expect(sources.has(a.source)).toBe(true);
    }
  });
});

describe('the generator', () => {
  it('is deterministic: two runs give byte-identical output', async () => {
    const again = await generateCorpus();
    expect(again.files.map((f) => f.path)).toEqual(fresh.files.map((f) => f.path));
    for (const [i, f] of again.files.entries())
      expect(firstDifference(f.bytes, fresh.files[i]!.bytes), f.path).toBe(-1);
  });

  it('builds the whole corpus, the 1,000-page document included, in seconds', () => {
    console.log(`corpus generated in ${(generationMs / 1000).toFixed(1)} s`);
    expect(generationMs).toBeLessThan(30_000);
  });

  it('matches what is in out/: the committed files are a fresh generation', async () => {
    for (const f of fresh.files) {
      const committed = manifest.documents.find((d) => d.file === f.path)?.inRepository ?? true;
      if (!committed && !onDisk(f.path)) continue;
      expect(
        onDisk(f.path),
        `${f.path} is missing: run pnpm --filter @docedit/corpus generate`,
      ).toBe(true);
      expect(
        firstDifference(await read(f.path), f.bytes),
        `${f.path} is stale: run pnpm --filter @docedit/corpus generate`,
      ).toBe(-1);
    }
  });

  it('keeps the large documents out of git and the small ones in', async () => {
    const ignore = new TextDecoder().decode(await read('.gitignore'));
    for (const d of manifest.documents) expect(ignore.includes(`/${d.file}`)).toBe(!d.inRepository);
    expect(manifest.documents.filter((d) => d.inRepository).map((d) => d.name)).toEqual([
      'pages-1',
      'form-fields',
      'pages-20',
    ]);
  });

  it('writes every file in the layout Prettier gives it', () => {
    const env = JSON.parse(new TextDecoder().decode(freshFile('pages-1.cdm.json'))) as JsonEnvelope;
    expect(serializeDocument(env as never)).toBe(
      new TextDecoder().decode(freshFile('pages-1.cdm.json')),
    );
  });
});

describe('the manifest', () => {
  it('has the canonical hash, file hash and size of every document', async () => {
    for (const d of manifest.documents) {
      const bytes = onDisk(d.file) ? await read(d.file) : freshFile(d.file);
      expect(bytes.length, d.name).toBe(d.fileBytes);
      expect(await sha256HexBytes(bytes), d.name).toBe(d.fileSha256);
      const env = JSON.parse(new TextDecoder().decode(bytes)) as JsonEnvelope;
      expect(await documentHash(env), d.name).toBe(d.documentHash);
    }
  });

  it('has the hash and size of every asset, and every asset is a PNG file', async () => {
    for (const a of manifest.assets) {
      const bytes = await read(a.file);
      expect(bytes.length).toBe(a.bytes);
      expect(await sha256HexBytes(bytes)).toBe(a.sha256);
      expect([...bytes.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
      expect(a.id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
    }
  });

  it('lists as attached exactly the assets each document refers to', async () => {
    for (const d of manifest.documents) {
      const text = JSON.stringify(await documentJson(d.name));
      const used = new Set(manifest.assets.map((a) => a.id).filter((id) => text.includes(id)));
      expect(new Set(d.assets), d.name).toEqual(used);
    }
  });

  it('carries the fingerprint of the current corpus version', async () => {
    expect(await fingerprintOf(manifest)).toBe(manifest.fingerprint);
    expect(
      fresh.fingerprint,
      'the output changed: add a corpus version (src/generate/version.ts)',
    ).toBe(CURRENT.fingerprint);
    expect(manifest.version).toBe(CURRENT.version);
    expect(manifest.history).toEqual(CORPUS_HISTORY);
    CORPUS_HISTORY.forEach((v, i) => expect(v.version).toBe(i + 1));
    expect(new Set(CORPUS_HISTORY.map((v) => v.fingerprint)).size).toBe(CORPUS_HISTORY.length);
  });
});

describe('coverage of FND-006', () => {
  const union = (names: readonly string[]): Set<string> =>
    new Set(manifest.documents.filter((d) => names.includes(d.name)).flatMap((d) => d.features));

  /** The constructs FND-006 and the task that built the corpus name, as feature identifiers. */
  const REQUIRED: Record<string, readonly string[]> = {
    'named styles with basedOn chains': [
      'styles.named.paragraph',
      'styles.named.character',
      'styles.named.table',
      'styles.basedOnChain.paragraph',
    ],
    'multi-level numbering: three levels, two lists on one definition, a restart': [
      'numbering.numbered',
      'numbering.threeLevels',
      'numbering.twoListsOneDefinition',
      'numbering.restart',
    ],
    'tables: longer than a page, row and column spans, header rows': [
      'tables',
      'tables.longerThanPage',
      'tables.rowspan',
      'tables.colspan',
      'tables.headerRows',
    ],
    'inline images and block figures with captions': [
      'images.inline',
      'figures',
      'figures.caption',
    ],
    'footnotes, headers and footers with page fields': [
      'footnotes',
      'headers',
      'footers',
      'fields.page',
      'fields.pageCount',
      'fields.inHeaderFooter',
    ],
    'cross-reference and sequence fields, bookmarks': ['fields.ref', 'fields.seq', 'bookmarks'],
    'inline and display math': ['math.inline', 'math.display'],
    'CJK text in Chinese, Japanese and Korean': [
      'cjk.zh',
      'cjk.ja',
      'cjk.ko',
      'cjk.han',
      'cjk.kana',
      'cjk.hangul',
    ],
    'very long paragraphs': ['paragraphs.over5000'],
    'regions, inherit and restricted': ['regions.inherit', 'regions.restricted'],
    'section breaks with a second page setup': ['sections', 'sections.secondPageSetup'],
    'the fields feature: form fields with role placeholders': [
      'requires.fields',
      'fields.form',
      'fields.roles',
      'fields.form.assigned',
    ],
  };

  it.each(Object.entries(REQUIRED))('covers %s', (_, features) => {
    const all = union(documentNames);
    for (const f of features) expect(all.has(f), f).toBe(true);
  });

  it('covers everything but the fields feature in the documents kept in the repository', () => {
    const committed = union(['pages-1', 'pages-20']);
    for (const features of Object.values(REQUIRED))
      for (const f of features)
        if (!f.startsWith('requires.') && !f.startsWith('fields.form') && f !== 'fields.roles')
          expect(committed.has(f), f).toBe(true);
  });

  it('keeps the size documents free of optional features, so every reader can open them', () => {
    for (const d of manifest.documents)
      expect(d.requires).toEqual(d.name === 'form-fields' ? ['fields'] : []);
  });

  it('has the same construct mix at every size from 20 pages up', () => {
    const base = new Set(documentEntry('pages-100').features);
    for (const name of ['pages-300', 'pages-1000'])
      for (const f of base)
        expect(documentEntry(name).features.includes(f), `${name}: ${f}`).toBe(true);
  });
});

describe('loadDocument', () => {
  it('returns the document, its attached assets and the corpus stamp', async () => {
    const doc = await loadDocument('pages-1');
    expect(doc.envelope.cdm).toBe(1);
    expect([...doc.attachedAssets]).toEqual(documentEntry('pages-1').assets);
    expect(doc.assets.map((a) => a.entry.id)).toEqual(documentEntry('pages-1').assets);
    expect(doc.corpus.version).toBe(corpusVersion);
    expect(serializeDocument(doc.envelope)).toBe(
      new TextDecoder().decode(await read(doc.entry.file)),
    );
    expect(documentFile('pages-1')).toBe('out/pages-1.cdm.json');
  });

  it('loads a large document without the file on disk, checked against the manifest', async () => {
    const doc = await loadDocument('pages-1000');
    expect(await documentHash(doc.envelope as unknown as JsonEnvelope)).toBe(
      documentEntry('pages-1000').documentHash,
    );
  });

  it('refuses an unknown name', async () => {
    await expect(loadDocument('pages-2')).rejects.toThrow(/no corpus document/);
  });
});
