/**
 * Builds the asset worker's sandbox image with Podman (BE-043; ADR 0043):
 *
 *   node services/asset-worker/scripts/build-image.ts
 *
 * The build context is staged in a temporary directory and holds only what the sandbox runs: the
 * Containerfile, `src/sandbox/` (which imports nothing outside itself but Node.js built-ins and the
 * decoders; test/boundaries.test.ts checks this), and the decoders pngjs, jpeg-js and omggif copied
 * out of the workspace's node_modules. No supervisor code, configuration or credentials go in.
 * The project's NOTICE and the third-party notices of the decoders are generated into the context
 * and copied to /opt/docedit/ (FND-011 criterion 3).
 * The tag is DOCEDIT_ASSET_IMAGE or the default of src/sandbox-podman.ts. Prints the image
 * identifier and size.
 */
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { containerCli } from '../src/container.ts';
import { IMAGE } from '../src/sandbox-podman.ts';

export const DECODERS = ['pngjs', 'jpeg-js', 'omggif'] as const;

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');

/**
 * The third-party notices of the image's npm packages, in the format of the release's notices
 * (scripts/release/notices.ts): name, version, licence, and every licence, copying and notice file
 * each package publishes. `dir` holds the packages as they go into the image.
 */
export function thirdPartyNotices(dir: string, names: readonly string[]): string {
  const parts = [
    '# Third-party notices for the asset worker sandbox image',
    '',
    'Generated by services/asset-worker/scripts/build-image.ts from the npm packages this image contains. Each one, its licence, and its licence and notice files as published. Node.js and the Debian base system come with the base image and keep their own licence files there (/usr/local/LICENSE, /usr/share/doc/*/copyright).',
    '',
  ];
  for (const name of [...names].sort()) {
    const pkg = join(dir, name);
    const manifest = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')) as {
      version?: string;
      license?: string;
    };
    parts.push(
      `## ${name} ${manifest.version ?? ''}`.trimEnd(),
      '',
      `Licence: ${manifest.license ?? 'UNKNOWN'}`,
      '',
    );
    const files = readdirSync(pkg, { withFileTypes: true })
      .filter((e) => e.isFile() && /^(licen[cs]e|copying|notice)/i.test(e.name))
      .map((e) => e.name)
      .sort();
    for (const f of files) parts.push('```', readFileSync(join(pkg, f), 'utf8').trim(), '```', '');
    if (!files.length) parts.push('The published package has no licence or notice file.', '');
  }
  return `${parts.join('\n')}\n`;
}

/** Stages the build context; returns its directory. */
export function stageContext(): string {
  const dir = mkdtempSync(join(tmpdir(), 'docedit-asset-image-'));
  cpSync(join(root, 'Containerfile'), join(dir, 'Containerfile'));
  const src = join(root, 'src', 'sandbox');
  for (const f of readdirSync(src))
    if (f.endsWith('.ts') && !f.endsWith('.test.ts')) cpSync(join(src, f), join(dir, 'sandbox', f));
  writeFileSync(join(dir, 'package.json'), '{ "private": true, "type": "module" }\n');
  const req = createRequire(join(root, 'package.json'));
  for (const name of DECODERS) {
    const pkg = realpathSync(dirname(req.resolve(`${name}/package.json`)));
    cpSync(pkg, join(dir, 'node_modules', name), { recursive: true, dereference: true });
  }
  // The notices are written from the packages just copied, so they name what the image holds.
  cpSync(join(root, '..', '..', 'NOTICE'), join(dir, 'NOTICE'));
  writeFileSync(
    join(dir, 'THIRD-PARTY-NOTICES.md'),
    thirdPartyNotices(join(dir, 'node_modules'), DECODERS),
  );
  return dir;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const cli = containerCli();
  const dir = stageContext();
  try {
    const build = spawnSync(
      cli,
      ['build', '--pull=missing', '-f', join(dir, 'Containerfile'), '-t', IMAGE, dir],
      {
        stdio: 'inherit',
      },
    );
    if (build.status !== 0) process.exit(build.status ?? 1);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  const inspect = spawnSync(cli, ['image', 'inspect', IMAGE, '--format', '{{.Id}} {{.Size}}'], {
    encoding: 'utf8',
  });
  console.log(`${IMAGE}: ${inspect.stdout.trim()}`);
}
