# Writes TRACEABILITY.md (FND-014): each requirement R1 to R15 (00 §4) mapped to the stories that
# implement it and to the test suites that prove it, taken from the stories' Requirements field and
# their Evidence lines. A requirement with no story, or with no test yet, is shown as a gap.
# Usage: pwsh docs/stories/tools/traceability.ps1
param(
  [string]$Dir = (Join-Path $PSScriptRoot '..'),
  [string]$Out = (Join-Path $PSScriptRoot '..\TRACEABILITY.md')
)
$prefixes = 'FND|SPK|FE|CDM|SYN|PRO|BE|PRM|HIS|EXP|SEC|FRW|UX|WASM'
$titles = [ordered]@{
  R1 = 'Word-like editing'; R2 = 'One custom element, own shadow root'; R3 = 'Region permissions'; R4 = 'History';
  R5 = 'Export (PDF by LaTeX, LaTeX bundle, DOCX)'; R6 = 'Loose coupling through DEP'; R7 = 'Collaboration and convergence';
  R8 = 'Comments and suggestions'; R9 = 'Scale'; R10 = 'Security and tenancy'; R11 = 'Accessibility'; R12 = 'Browser support';
  R13 = 'Fields, rules and workflow'; R14 = 'Feature parity'; R15 = 'All-round package'
}

$stories = @()
foreach ($f in Get-ChildItem $Dir -Filter *.md | Where-Object { $_.Name -notin @('README.md','BACKLOG.md','PROGRESS.md','TRACEABILITY.md') }) {
  $cur = $null
  foreach ($line in (Get-Content $f.FullName -Encoding UTF8)) {
    if ($line -match '^#{1,3}\s' -and $cur) { $stories += $cur; $cur = $null }
    if ($line -match "^###\s+(($prefixes)-\d{3})\s") { $cur = [pscustomobject]@{ Id=$Matches[1]; Reqs=@(); Total=0; Ticked=0; Tests=@() }; continue }
    if (-not $cur) { continue }
    if ($line -match 'Requirements:\*\*\s*([^·]+)') {
      $text = $Matches[1]
      foreach ($m in [regex]::Matches($text, 'R(\d+)(?:\s*to\s*R(\d+))?')) {
        $a = [int]$m.Groups[1].Value; $b = if ($m.Groups[2].Success) { [int]$m.Groups[2].Value } else { $a }
        for ($k = $a; $k -le $b; $k++) { $cur.Reqs += "R$k" }
      }
      if ($text -match '\ball\b') { $cur.Reqs += $titles.Keys }
    }
    if ($line -match '^\s*-\s\[[ xX]\]') { $cur.Total++ }
    if ($line -match '^\s*-\s\[[xX]\]') { $cur.Ticked++ }
    if ($line -match '^\*\*Evidence:\*\*') { foreach ($m in [regex]::Matches($line, '[\w./-]+\.test\.ts')) { $cur.Tests += $m.Value } }
  }
  if ($cur) { $stories += $cur }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Requirements traceability')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("Generated by ``tools/traceability.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm') (FND-014). Stories come from each story's **Requirements** field. Tests come from the **Evidence** lines of stories with ticked criteria. A requirement without a story, or without any test yet, is marked as a gap.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Req | Requirement | Stories | Done | Test suites | Gap |')
[void]$sb.AppendLine('|---|---|---:|---:|---|---|')
foreach ($r in $titles.Keys) {
  $s = @($stories | Where-Object { $_.Reqs -contains $r })
  $done = @($s | Where-Object { $_.Total -gt 0 -and $_.Ticked -eq $_.Total }).Count
  $tests = @($s | ForEach-Object { $_.Tests } | Sort-Object -Unique)
  $gap = if ($s.Count -eq 0) { 'no story' } elseif ($tests.Count -eq 0) { 'no test yet' } else { '' }
  $testText = if ($tests.Count) { ($tests | ForEach-Object { "``$_``" }) -join ', ' } else { '' }
  [void]$sb.AppendLine("| $r | $($titles[$r]) | $($s.Count) | $done | $testText | $gap |")
}
Set-Content -Path $Out -Value $sb.ToString() -Encoding UTF8
"Wrote $Out"
