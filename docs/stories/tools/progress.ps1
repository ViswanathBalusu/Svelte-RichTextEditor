# Writes PROGRESS.md: per epic and phase, how many stories are done (every acceptance criterion
# ticked) and how many criteria are ticked. A story counts as done only when all its criteria are [x].
# Usage: pwsh docs/stories/tools/progress.ps1
param(
  [string]$Dir = (Join-Path $PSScriptRoot '..'),
  [string]$Out = (Join-Path $PSScriptRoot '..\PROGRESS.md')
)
$prefixes = 'FND|SPK|FE|CDM|SYN|PRO|BE|PRM|HIS|EXP|SEC|FRW|UX|WASM'
$epicOrder = @('FND','SPK','CDM','SYN','PRM','PRO','BE','SEC','FE','UX','HIS','EXP','FRW','WASM')
$phaseOrder = @('0','1a','1b','2','3','4','cond')

$stories = @()
foreach ($f in Get-ChildItem $Dir -Filter *.md | Where-Object { $_.Name -notin @('README.md','BACKLOG.md','PROGRESS.md') }) {
  $lines = Get-Content $f.FullName -Encoding UTF8
  $cur = $null
  foreach ($line in $lines) {
    if ($line -match '^#{1,3}\s' -and $cur) { $stories += $cur; $cur = $null }
    if ($line -match "^###\s+(($prefixes)-\d{3})\s+(.+)$") {
      $cur = [pscustomobject]@{ Id=$Matches[1]; Epic=$Matches[2]; Title=$Matches[3].Trim(); Phase=''; Total=0; Ticked=0 }
      continue
    }
    if ($cur) {
      if (-not $cur.Phase -and $line -match '^\|\s*(story|enabler|spike|decision)\s*\|\s*([^|]+?)\s*\|') { $cur.Phase = $Matches[2] }
      if ($line -match '^\s*-\s\[[ xX]\]') { $cur.Total++ }
      if ($line -match '^\s*-\s\[[xX]\]') { $cur.Ticked++ }
    }
  }
  if ($cur) { $stories += $cur }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Progress')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("Generated by ``tools/progress.ps1`` on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). A story is done when every acceptance criterion is ticked in its epic file; the evidence is in the story's **Evidence** line. Cells read done/total stories.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('| Epic | ' + ($phaseOrder -join ' | ') + ' | Done | Criteria ticked |')
[void]$sb.AppendLine('|---|' + (($phaseOrder | ForEach-Object { '---:' }) -join '|') + '|---:|---:|')
foreach ($e in $epicOrder) {
  $g = $stories | Where-Object { $_.Epic -eq $e }
  $cells = foreach ($p in $phaseOrder) {
    $gp = @($g | Where-Object { $_.Phase -eq $p })
    if ($gp.Count) { "$(@($gp | Where-Object { $_.Total -gt 0 -and $_.Ticked -eq $_.Total }).Count)/$($gp.Count)" } else { '' }
  }
  $done = @($g | Where-Object { $_.Total -gt 0 -and $_.Ticked -eq $_.Total }).Count
  $ac = ($g | Measure-Object -Property Ticked -Sum).Sum
  $act = ($g | Measure-Object -Property Total -Sum).Sum
  [void]$sb.AppendLine("| $e | " + ($cells -join ' | ') + " | $done/$(@($g).Count) | $ac/$act |")
}
$all = @($stories)
$cellsAll = foreach ($p in $phaseOrder) { $gp = @($all | Where-Object { $_.Phase -eq $p }); "$(@($gp | Where-Object { $_.Total -gt 0 -and $_.Ticked -eq $_.Total }).Count)/$($gp.Count)" }
$doneAll = @($all | Where-Object { $_.Total -gt 0 -and $_.Ticked -eq $_.Total }).Count
[void]$sb.AppendLine("| **All** | " + ($cellsAll -join ' | ') + " | **$doneAll/$($all.Count)** | $((($all | Measure-Object -Property Ticked -Sum).Sum))/$((($all | Measure-Object -Property Total -Sum).Sum)) |")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Partly done')
[void]$sb.AppendLine('')
$partial = $all | Where-Object { $_.Ticked -gt 0 -and $_.Ticked -lt $_.Total }
if ($partial) {
  [void]$sb.AppendLine('| Story | Title | Phase | Criteria ticked |')
  [void]$sb.AppendLine('|---|---|---|---|')
  foreach ($s in $partial) { [void]$sb.AppendLine("| $($s.Id) | $($s.Title) | $($s.Phase) | $($s.Ticked)/$($s.Total) |") }
} else { [void]$sb.AppendLine('None.') }
Set-Content -Path $Out -Value $sb.ToString() -Encoding UTF8
"Wrote $Out ($doneAll of $($all.Count) stories done)"
