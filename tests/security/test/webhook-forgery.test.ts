/**
 * SEC-020 (10 §3.2 forged webhooks and server-side request forgery; 05 §7): what a receiver can
 * trust, and what the dispatcher's egress can reach.
 *
 * Criterion 1 runs the reference receiver of the reference host (apps/reference-host, UX-098)
 * against a delivery signed by the service's own signer, so the two implementations must agree.
 * Criterion 2 is the secret rotation, seen at the receiver. Criterion 3 and criterion 4 drive the
 * egress proxy (BE-056) with a resolver and a connector that record every call; a refused target
 * must show zero connections. Criterion 5 (the network policy that makes the proxy the only route
 * out) and criterion 6 (no secret in logs and metrics, the logs part is BE-055's own test) are not
 * proved here; see the story's Notes.
 *
 * Every key is generated by the test. No real host is contacted: the connectors are fakes.
 */
import fc from 'fast-check';
import { describe, expect, it } from 'vitest';
import {
  signDelivery,
  generateSecret,
} from '../../../services/document-service/src/control-plane/webhook-signing.ts';
import {
  EgressProxy,
  type ConnectInput,
  type ConnectResult,
  type Connector,
  type Resolver,
  type TransportResult,
} from '../../../services/document-service/src/control-plane/webhook-egress.ts';
import {
  MemorySeenStore,
  WebhookReceiver,
  type ReceivedEvent,
} from '../../../apps/reference-host/src/lib/server/webhook-receiver.ts';

const NOW = 1_800_000_000;
const PUBLIC = '93.184.216.34';
const EVENT = JSON.stringify({
  specversion: '1.0',
  type: 'dep.document.changed.v1',
  subject: '0190c8a4-1b2c-7d3e-8f40-123456789abc',
  data: { seq: 1 },
});

function receiverWith(
  secrets: () => readonly string[],
  now: () => number,
): { receiver: WebhookReceiver; queue: ReceivedEvent[] } {
  const queue: ReceivedEvent[] = [];
  const receiver = new WebhookReceiver({
    secrets,
    seen: new MemorySeenStore(),
    queue: { push: (e) => queue.push(e) },
    now,
  });
  return { receiver, queue };
}

function signedWith(secret: string, id: string, timestamp: number, body: string): Headers {
  return new Headers(signDelivery({ id, timestamp, body, secrets: [secret] }));
}

describe('SEC-020 criterion 1: the reference receiver accepts only the genuine delivery', () => {
  const secret = generateSecret();
  const id = 'msg_genuine_0001';

  it('accepts a genuine delivery once and queues it', () => {
    const { receiver, queue } = receiverWith(
      () => [secret],
      () => NOW,
    );
    expect(receiver.receive(signedWith(secret, id, NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    expect(queue.map((e) => e.webhookId)).toEqual([id]);
  });

  it('refuses a tampered body with 401 and queues nothing', () => {
    const { receiver, queue } = receiverWith(
      () => [secret],
      () => NOW,
    );
    const tampered = EVENT.replace('"seq":1', '"seq":2');
    expect(receiver.receive(signedWith(secret, id, NOW, EVENT), tampered)).toEqual({
      status: 401,
      reason: 'bad-signature',
    });
    expect(queue).toHaveLength(0);
  });

  it('refuses a delivery signed with a wrong secret with 401', () => {
    const { receiver, queue } = receiverWith(
      () => [secret],
      () => NOW,
    );
    const forged = signedWith(generateSecret(), id, NOW, EVENT);
    expect(receiver.receive(forged, EVENT)).toEqual({ status: 401, reason: 'bad-signature' });
    expect(queue).toHaveLength(0);
  });

  it('refuses a timestamp older than five minutes with 400, and accepts one exactly five minutes old', () => {
    const atEdge = receiverWith(
      () => [secret],
      () => NOW + 300,
    );
    expect(atEdge.receiver.receive(signedWith(secret, id, NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    const stale = receiverWith(
      () => [secret],
      () => NOW + 301,
    );
    expect(stale.receiver.receive(signedWith(secret, id, NOW, EVENT), EVENT)).toEqual({
      status: 400,
      reason: 'stale-timestamp',
    });
    expect(stale.queue).toHaveLength(0);
  });

  it('detects a replayed webhook-id by identifier and queues the event once', () => {
    const { receiver, queue } = receiverWith(
      () => [secret],
      () => NOW,
    );
    const headers = signedWith(secret, id, NOW, EVENT);
    expect(receiver.receive(headers, EVENT)).toEqual({ status: 202, duplicate: false });
    expect(receiver.receive(headers, EVENT)).toEqual({ status: 202, duplicate: true });
    expect(queue).toHaveLength(1);
  });

  it('does not let a tampered copy of a seen identifier pass, and does not mark a refused one as seen', () => {
    const { receiver, queue } = receiverWith(
      () => [secret],
      () => NOW,
    );
    const tampered = EVENT.replace('"seq":1', '"seq":9');
    // A tampered body under a fresh identifier is refused and must not poison that identifier.
    expect(receiver.receive(signedWith(secret, id, NOW, EVENT), tampered)).toEqual({
      status: 401,
      reason: 'bad-signature',
    });
    expect(receiver.receive(signedWith(secret, id, NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    // The genuine identifier, replayed with a changed body, is refused by the signature.
    expect(receiver.receive(signedWith(secret, id, NOW, EVENT), tampered)).toEqual({
      status: 401,
      reason: 'bad-signature',
    });
    expect(queue).toHaveLength(1);
  });
});

describe('SEC-020 criterion 2: a rotated secret verifies until it is retired', () => {
  it('accepts a delivery signed by either of two active secrets', () => {
    const oldSecret = generateSecret();
    const newSecret = generateSecret();
    const { receiver, queue } = receiverWith(
      () => [oldSecret, newSecret],
      () => NOW,
    );
    expect(receiver.receive(signedWith(oldSecret, 'msg_old', NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    expect(receiver.receive(signedWith(newSecret, 'msg_new', NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    expect(queue).toHaveLength(2);
  });

  it('after the old secret is retired, a delivery signed only with it is refused and the new one is accepted', () => {
    const oldSecret = generateSecret();
    const newSecret = generateSecret();
    let active: string[] = [oldSecret, newSecret];
    const { receiver, queue } = receiverWith(
      () => active,
      () => NOW,
    );
    active = [newSecret];
    expect(receiver.receive(signedWith(oldSecret, 'msg_retired', NOW, EVENT), EVENT)).toEqual({
      status: 401,
      reason: 'bad-signature',
    });
    expect(receiver.receive(signedWith(newSecret, 'msg_current', NOW, EVENT), EVENT)).toEqual({
      status: 202,
      duplicate: false,
    });
    expect(queue.map((e) => e.webhookId)).toEqual(['msg_current']);
  });

  it('refuses every delivery when no secret is active', () => {
    const secret = generateSecret();
    const { receiver } = receiverWith(
      () => [],
      () => NOW,
    );
    expect(receiver.receive(signedWith(secret, 'msg_none', NOW, EVENT), EVENT)).toEqual({
      status: 401,
      reason: 'no-secret',
    });
  });
});

/** A resolver that records every host it is asked for; a call with no answer is an error. */
function resolverOf(map: Record<string, readonly string[]>): Resolver & { calls: string[] } {
  const calls: string[] = [];
  return {
    calls,
    resolve(host: string): Promise<readonly string[]> {
      calls.push(host);
      const got = map[host];
      return got === undefined ? Promise.reject(new Error('no such host')) : Promise.resolve(got);
    },
  };
}

/** A resolver that answers in turn, then keeps answering with the last answer. */
function resolverSequence(
  answers: ReadonlyArray<readonly string[]>,
): Resolver & { calls: string[] } {
  const calls: string[] = [];
  return {
    calls,
    resolve(host: string): Promise<readonly string[]> {
      calls.push(host);
      const index = Math.min(calls.length - 1, answers.length - 1);
      return Promise.resolve(answers[index] ?? []);
    },
  };
}

/** A connector that reports the checked address and answers 200; every call is recorded. */
function honestConnector(): Connector & { calls: ConnectInput[] } {
  const calls: ConnectInput[] = [];
  return {
    calls,
    send(input: ConnectInput): Promise<ConnectResult> {
      calls.push(input);
      return Promise.resolve({ remoteAddress: input.address, status: 200, location: undefined });
    },
  };
}

/** A connector that answers the first call with a redirect to `location`, then 200. */
function redirectingConnector(location: string): Connector & { calls: ConnectInput[] } {
  const calls: ConnectInput[] = [];
  return {
    calls,
    send(input: ConnectInput): Promise<ConnectResult> {
      calls.push(input);
      if (calls.length === 1)
        return Promise.resolve({ remoteAddress: input.address, status: 302, location });
      return Promise.resolve({ remoteAddress: input.address, status: 200, location: undefined });
    },
  };
}

function reasonOf(result: TransportResult): string {
  if (result.ok) throw new Error('the delivery was not refused');
  return result.reason;
}

const REFUSED_CLASSES = [
  'loopback',
  'private',
  'link_local',
  'metadata',
  'unspecified',
  'not_an_address',
];

describe('SEC-020 criterion 3: targets in the named ranges are refused, in every spelling, with no connection', () => {
  // Each target is a URL as a caller would write it. The WHATWG URL parser turns the decimal,
  // octal and hexadecimal spellings of an IPv4 address into dotted form before the policy sees them.
  const TARGETS = [
    'http://127.0.0.1/hook',
    'http://[::1]/hook',
    'http://10.0.0.1/hook',
    'http://172.16.0.1/hook',
    'http://172.31.255.254/hook',
    'http://192.168.0.1/hook',
    'http://169.254.169.254/latest/meta-data',
    'http://[fc00::1]/hook',
    'http://[fd00:ec2::254]/hook',
    'http://[fe80::1]/hook',
    'http://[::ffff:127.0.0.1]/hook',
    'http://[::ffff:10.0.0.1]/hook',
    'http://[::ffff:169.254.169.254]/hook',
    'http://[::ffff:7f00:1]/hook',
    'http://[0:0:0:0:0:ffff:a9fe:a9fe]/hook',
    'http://2130706433/hook',
    'http://0177.0.0.1/hook',
    'http://0x7f000001/hook',
    'http://0x7f.0.0.1/hook',
    'http://2852060926/hook',
    'http://0xa9fea9fe/hook',
    'http://localhost/hook',
    'http://localhost.:8080/hook',
  ];

  it.each(TARGETS)('refuses %s and makes no connection', async (target) => {
    const resolver = resolverOf({});
    const connector = honestConnector();
    const proxy = new EgressProxy({ resolver, connector, maxRedirects: 3 });
    const got = await proxy.deliver({ url: target, headers: {}, body: '{}' });
    expect(REFUSED_CLASSES).toContain(reasonOf(got));
    expect(connector.calls).toHaveLength(0);
    expect(resolver.calls).toHaveLength(0);
  });

  it('refuses a private, loopback or link-local address written as decimal, hexadecimal or dotted (property)', async () => {
    const octet = fc.integer({ min: 0, max: 255 });
    const privateOctets = fc.oneof(
      fc.tuple(fc.constant(10), octet, octet, octet),
      fc.tuple(fc.constant(127), octet, octet, octet),
      fc.tuple(fc.constant(192), fc.constant(168), octet, octet),
      fc.tuple(fc.constant(172), fc.integer({ min: 16, max: 31 }), octet, octet),
      fc.tuple(fc.constant(169), fc.constant(254), octet, octet),
    );
    await fc.assert(
      fc.asyncProperty(
        privateOctets,
        fc.constantFrom('decimal', 'hex', 'dotted'),
        async (o, style) => {
          const [a, b, c, d] = o;
          const value = ((a << 24) >>> 0) + (b << 16) + (c << 8) + d;
          const spelled =
            style === 'decimal'
              ? String(value)
              : style === 'hex'
                ? `0x${value.toString(16)}`
                : o.join('.');
          const connector = honestConnector();
          const proxy = new EgressProxy({ resolver: resolverOf({}), connector, maxRedirects: 3 });
          const got = await proxy.deliver({ url: `http://${spelled}/hook`, headers: {}, body: '' });
          expect(REFUSED_CLASSES).toContain(reasonOf(got));
          expect(connector.calls).toHaveLength(0);
        },
      ),
      { numRuns: 200 },
    );
  });

  it('refuses a name that resolves into a private range, and a name of loopback, with no connection', async () => {
    const resolver = resolverOf({ 'internal.example.test': ['10.0.0.5'] });
    const connector = honestConnector();
    const proxy = new EgressProxy({ resolver, connector, maxRedirects: 3 });
    expect(
      reasonOf(
        await proxy.deliver({ url: 'https://internal.example.test/in', headers: {}, body: '' }),
      ),
    ).toBe('private');
    expect(
      reasonOf(await proxy.deliver({ url: 'https://svc.localhost/in', headers: {}, body: '' })),
    ).toBe('loopback');
    expect(connector.calls).toHaveLength(0);
  });
});

describe('SEC-020 criterion 4: a name that moves to a private address, and a redirect to one, are both refused', () => {
  it('refuses a name whose answer contains a public and a private address in one lookup', async () => {
    const resolver = resolverOf({ 'mixed.example.test': [PUBLIC, '127.0.0.1'] });
    const connector = honestConnector();
    const proxy = new EgressProxy({ resolver, connector, maxRedirects: 3 });
    expect(
      reasonOf(
        await proxy.deliver({ url: 'https://mixed.example.test/in', headers: {}, body: '' }),
      ),
    ).toBe('loopback');
    expect(connector.calls).toHaveLength(0);
  });

  it('refuses a name that resolved to a public address earlier and to a private one on the next delivery (rebinding)', async () => {
    const resolver = resolverSequence([[PUBLIC], ['10.0.0.9']]);
    const connector = honestConnector();
    const proxy = new EgressProxy({ resolver, connector, maxRedirects: 3 });
    const first = await proxy.deliver({
      url: 'https://rebind.example.test/in',
      headers: {},
      body: '',
    });
    expect(first).toEqual({ ok: true, status: 200, hops: 0 });
    const second = await proxy.deliver({
      url: 'https://rebind.example.test/in',
      headers: {},
      body: '',
    });
    expect(reasonOf(second)).toBe('private');
    // Only the public address was ever connected to; the private one was refused before connecting.
    expect(connector.calls.map((c) => c.address)).toEqual([PUBLIC]);
  });

  it('refuses a public target that redirects to the metadata address or to a loopback spelling, before a second request', async () => {
    for (const location of ['http://169.254.169.254/latest/meta-data', 'http://2130706433/hook']) {
      const resolver = resolverOf({ 'redirect.example.test': [PUBLIC] });
      const connector = redirectingConnector(location);
      const proxy = new EgressProxy({ resolver, connector, maxRedirects: 3 });
      const got = await proxy.deliver({
        url: 'https://redirect.example.test/in',
        headers: {},
        body: '{}',
      });
      expect(REFUSED_CLASSES).toContain(reasonOf(got));
      expect(connector.calls).toHaveLength(1);
    }
  });
});
