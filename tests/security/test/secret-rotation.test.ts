/**
 * SEC-048 criteria 3 to 5 (10 §3.7 "secrets are managed and rotated with overlap"): the overlap
 * during which an old and a new webhook secret or service credential both work, the removal of a
 * tenant verification key, and the revocation of a compromised service credential.
 *
 * Criteria 1, 2 and 6 are not proved here. They need the repository scan in CI, the container's
 * runtime environment and a recorded rehearsal of the rotation procedure, none of which is in this
 * tree. See the story's Notes.
 *
 * The tests drive the service's own verifiers (webhook-signing.ts, TokenService) over the in-memory
 * tenant registry, which reads storage on every call, as the PostgreSQL one does. Every key here is
 * generated by the test; no real secret is used.
 */
import { randomUUID } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import {
  signDelivery,
  verifyDelivery,
  generateSecret,
} from '../../../services/document-service/src/control-plane/webhook-signing.ts';
import {
  MemoryTenantRegistry,
  hashSecret,
} from '../../../services/document-service/src/control-plane/tenants.ts';
import {
  newApiKey,
  signingKey,
  TokenService,
} from '../../../services/document-service/src/control-plane/tokens.ts';
import { MemoryUserDirectory } from '../../../services/document-service/src/control-plane/users.ts';
import { keyPair, signJws } from './support/jws.ts';

const SERVICE = 'https://docs.example.test';
const ISSUER = 'https://host.example.test';

describe('SEC-048 criterion 3: a webhook secret rotated with an overlap', () => {
  const body = '{"type":"document.changed","data":{"doc":"d1"}}';
  const id = 'msg_0001';
  const now = 1_800_000_000;

  it('the overlap accepts the old and the new secret; after it only the new one works', () => {
    const oldSecret = generateSecret();
    const newSecret = generateSecret();
    const headers = signDelivery({ id, timestamp: now, body, secrets: [oldSecret, newSecret] });
    // During the overlap, a receiver that still knows only the old secret verifies the delivery,
    // and so does one that already knows only the new secret.
    expect(verifyDelivery({ headers, body, secrets: [oldSecret], now })).toEqual({ ok: true });
    expect(verifyDelivery({ headers, body, secrets: [newSecret], now })).toEqual({ ok: true });

    // After the overlap the sender signs with the new secret alone.
    const after = signDelivery({ id, timestamp: now, body, secrets: [newSecret] });
    expect(verifyDelivery({ headers: after, body, secrets: [newSecret], now })).toEqual({
      ok: true,
    });
    expect(verifyDelivery({ headers: after, body, secrets: [oldSecret], now })).toEqual({
      ok: false,
      reason: 'bad_signature',
    });
  });
});

describe('SEC-048 criterion 3: a service credential rotated with an overlap', () => {
  it('both API keys work until the old one expires, then only the new one works', async () => {
    let now = 1_800_000_000_000;
    const tenant = randomUUID();
    const registry = new MemoryTenantRegistry(() => now);
    await registry.putTenant(tenant, 'tenant');
    const tokens = new TokenService({
      registry,
      users: new MemoryUserDirectory(),
      serviceId: SERVICE,
      signing: signingKey(undefined, 'svc'),
      now: () => now,
    });

    const oldKey = newApiKey(tenant);
    const newKey = newApiKey(tenant);
    const overlapEnds = now + 60_000;
    await registry.addApiKey(tenant, {
      id: oldKey.id,
      secretHash: hashSecret(oldKey.secret),
      expiresAt: overlapEnds,
    });
    await registry.addApiKey(tenant, { id: newKey.id, secretHash: hashSecret(newKey.secret) });

    expect(await tokens.verifyService(oldKey.credential)).toEqual({
      tenant,
      credential: `key:${oldKey.id}`,
    });
    expect(await tokens.verifyService(newKey.credential)).toEqual({
      tenant,
      credential: `key:${newKey.id}`,
    });

    now = overlapEnds;
    await expect(tokens.verifyService(oldKey.credential)).rejects.toThrow(/expired/);
    expect((await tokens.verifyService(newKey.credential)).tenant).toBe(tenant);
  });
});

describe('SEC-048 criterion 4: a tenant verification key replaced', () => {
  it('tokens signed by the removed key are refused once it is removed, and the new key works', async () => {
    const now = Date.now();
    const tenant = randomUUID();
    const registry = new MemoryTenantRegistry(() => now);
    await registry.putTenant(tenant, 'tenant');
    const oldHost = keyPair('ES256');
    const newHost = keyPair('ES256');
    await registry.addKey(tenant, { kid: 'host-old', use: 'user', alg: 'ES256', jwk: oldHost.jwk });
    const tokens = new TokenService({
      registry,
      users: new MemoryUserDirectory(),
      serviceId: SERVICE,
      signing: signingKey(undefined, 'svc'),
      now: () => now,
    });
    const doc = randomUUID();
    const mint = (kid: string, key: ReturnType<typeof keyPair>) =>
      signJws(
        { alg: 'ES256', typ: 'JWT', kid },
        {
          iss: ISSUER,
          aud: SERVICE,
          iat: Math.floor(now / 1000),
          exp: Math.floor(now / 1000) + 300,
          jti: randomUUID(),
          tid: tenant,
          sub: 'ann',
          docs: { [doc]: 'editor' },
        },
        { key: key.privateKey },
      );

    const oldToken = mint('host-old', oldHost);
    expect((await tokens.verifyUser(oldToken)).tenant).toBe(tenant);

    // The replacement: register the new key, remove the old one.
    await registry.addKey(tenant, { kid: 'host-new', use: 'user', alg: 'ES256', jwk: newHost.jwk });
    await registry.removeKey(tenant, 'host-old');

    await expect(tokens.verifyUser(oldToken)).rejects.toThrow(/no key registered/);
    expect((await tokens.verifyUser(mint('host-new', newHost))).tenant).toBe(tenant);
  });
});

describe('SEC-048 criterion 5: a compromised service credential revoked', () => {
  it('a revoked API key is refused on the next call, with no restart', async () => {
    const now = Date.now();
    const tenant = randomUUID();
    const registry = new MemoryTenantRegistry(() => now);
    await registry.putTenant(tenant, 'tenant');
    const tokens = new TokenService({
      registry,
      users: new MemoryUserDirectory(),
      serviceId: SERVICE,
      signing: signingKey(undefined, 'svc'),
      now: () => now,
    });
    const key = newApiKey(tenant);
    await registry.addApiKey(tenant, { id: key.id, secretHash: hashSecret(key.secret) });
    expect((await tokens.verifyService(key.credential)).tenant).toBe(tenant);

    expect(await registry.removeApiKey(tenant, key.id)).toBe(true);
    await expect(tokens.verifyService(key.credential)).rejects.toThrow(/not registered/);
  });
});
