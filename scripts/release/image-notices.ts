/**
 * Notices inside a release image (FND-011 criterion 3; ADR 0044 §4). The release builds an image
 * from its Containerfile and then adds one layer on top of it that holds the project's NOTICE file
 * and the third-party notices of what the image contains, at /opt/docedit/. The layer is the same
 * for every image, so a service image that is added later gets it without a change to its own
 * Containerfile. An image whose own build context already writes both files (the asset worker's)
 * sets `noticesInContext` in scripts/release/distributables.ts and gets no layer.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { FontManifest, TexPackage } from './texlive.ts';

/** Where the two files are inside an image. */
export const NOTICES_DIR = '/opt/docedit';
export const NOTICE_FILE = 'NOTICE';
export const THIRD_PARTY_FILE = 'THIRD-PARTY-NOTICES.md';

/** The Containerfile of the layer, on top of the image that was built from the service's own file. */
export function overlayContainerfile(base: string): string {
  if (!/^[A-Za-z0-9][A-Za-z0-9._:/@-]*$/.test(base))
    throw new Error(`"${base}" is not an image reference`);
  return `FROM ${base}\nCOPY ${NOTICE_FILE} ${THIRD_PARTY_FILE} ${NOTICES_DIR}/\n`;
}

/**
 * The notices of the export worker's image: the TeX Live packages and the fonts that are read
 * from inside it. The licence texts of the TeX Live packages are not copied; the image says so.
 */
export function texliveNotices(
  title: string,
  tex: readonly TexPackage[],
  fonts: FontManifest | null,
): string {
  const parts = [
    `# Third-party notices for ${title}`,
    '',
    'Generated by scripts/release/image-notices.ts from what was read inside the image: `tlmgr info` for the TeX Live packages and fonts.json for the fonts.',
    '',
    '## TeX Live packages',
    '',
    'The licence is the `cat-license` field of the TeX Live catalogue. The licence texts of the packages are those of the TeX Live distribution and are not copied here.',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
  ];
  const sorted = [...tex].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const p of sorted) {
    const licence = p.licences.length ? p.licences.join(' ') : 'not stated in the catalogue';
    const version = p.catalogueVersion || `r${p.revision}`;
    parts.push(`| ${p.name} | ${version} | ${licence} |`);
  }
  parts.push('', '## Fonts', '');
  const rows: string[] = [];
  for (const f of fonts?.families ?? [])
    rows.push(
      `| ${f.name} | ${f.licence} | ${[f.regular, f.bold, f.italic, f.boldItalic].map((x) => x.file).join(', ')} |`,
    );
  if (fonts?.math) rows.push(`| ${fonts.math.name} | ${fonts.math.licence} | ${fonts.math.file} |`);
  if (rows.length) parts.push('| Family | Licence | Files |', '|---|---|---|', ...rows);
  else parts.push('The image lists no fonts.');
  return `${parts.join('\n')}\n`;
}

/** Writes the context of the layer: the Containerfile, NOTICE and the third-party notices. */
export function stageOverlayContext(
  dir: string,
  o: { base: string; root: string; thirdParty: string },
): string {
  mkdirSync(dir, { recursive: true });
  const notice = join(o.root, NOTICE_FILE);
  if (!existsSync(notice)) throw new Error(`${notice} does not exist`);
  copyFileSync(notice, join(dir, NOTICE_FILE));
  writeFileSync(join(dir, THIRD_PARTY_FILE), o.thirdParty);
  writeFileSync(join(dir, 'Containerfile'), overlayContainerfile(o.base));
  return join(dir, 'Containerfile');
}

/** The third-party notices that the release wrote for a service, from its notices file. */
export function readServiceNotices(file: string): string {
  if (!existsSync(file))
    throw new Error(`${file} does not exist; the release writes it before the image is built`);
  return readFileSync(file, 'utf8');
}
