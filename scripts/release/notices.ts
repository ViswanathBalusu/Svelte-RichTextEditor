/**
 * Third-party notices of one release artefact (FND-011 criterion 3, FND-012; ADR 0044 §4), in the
 * format of scripts/third-party-notices.ts, but from the packages that really ship: for a bundle
 * the packages found in it (scripts/supply-chain/bundle.ts), for a service the packages of its bill
 * of materials. Each entry has the name, version and licence, and every licence, copying and notice
 * file the package publishes. A package published without such a file says so, with the reason of
 * the recorded licence exception.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

export interface NoticeEntry {
  name: string;
  version: string;
  licence: string;
  dir: string | null;
  /** The recorded licence exception, when one applies. */
  exception?: string;
}

const NOTICE_FILE = /^(licen[cs]e|copying|notice)/i;

export function noticeFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && NOTICE_FILE.test(e.name))
    .map((e) => e.name)
    .sort();
}

/** The notices as Markdown, and the entries that ship without any licence or notice file. */
export function renderNotices(
  title: string,
  entries: readonly NoticeEntry[],
): { text: string; withoutFiles: string[] } {
  const parts = [
    `# Third-party notices for ${title}`,
    '',
    'Generated by scripts/release/notices.ts from the packages this artefact contains. Each one, its licence, and its licence and notice files as published.',
    '',
  ];
  const withoutFiles: string[] = [];
  const sorted = [...entries].sort((a, b) =>
    a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1,
  );
  for (const e of sorted) {
    parts.push(`## ${e.name} ${e.version}`, '', `Licence: ${e.licence}`, '');
    const files = e.dir ? noticeFiles(e.dir) : [];
    for (const f of files)
      parts.push('```', readFileSync(join(e.dir!, f), 'utf8').trim(), '```', '');
    if (!files.length) {
      withoutFiles.push(`${e.name}@${e.version}`);
      parts.push(
        e.exception
          ? `The published package has no licence or notice file. Recorded decision: ${e.exception}`
          : 'The published package has no licence or notice file.',
        '',
      );
    }
  }
  return { text: `${parts.join('\n')}\n`, withoutFiles };
}
