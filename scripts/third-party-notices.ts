/**
 * Writes the third-party notices of one workspace package's production dependencies (FND-011):
 * name, version, licence and the full licence and notice texts. It follows the package's
 * production closure across workspace packages (`workspace:` links), so that, for the element,
 * the dependencies of the editing core and the model (every ProseMirror module) are included.
 *
 * Release artefacts get their notices from what really ships instead (scripts/release/notices.ts:
 * the packages found in a bundle, which also covers devDependencies a bundler inlines, such as
 * pdfjs-dist in the element, or the packages of an image's bill of materials).
 *
 * Usage: node scripts/third-party-notices.ts <workspace package name> <output file>
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { flattenLicenceList, runLicenceList, workspaceClosure } from './release/walk.ts';

const [pkg, out] = process.argv.slice(2);
if (!pkg || !out) {
  console.error('usage: node scripts/third-party-notices.ts <package> <output file>');
  process.exit(2);
}
const root = resolve(import.meta.dirname, '..');
const closure = workspaceClosure(root, pkg).map((p) => p.name);
const all = flattenLicenceList(runLicenceList(root, closure)).sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);

const parts: string[] = [
  `# Third-party notices for ${pkg}`,
  '',
  `Generated by scripts/third-party-notices.ts from the production dependencies of ${closure.join(', ')}. Each dependency, its licence, and its licence and notice files as published.`,
  '',
];
for (const e of all) {
  parts.push(`## ${e.name} ${e.version}`, '', `Licence: ${e.licence}`, '');
  const dir = e.path;
  if (dir && existsSync(dir)) {
    for (const f of readdirSync(dir)
      .filter((x) => /^(licen[cs]e|copying|notice)/i.test(x))
      .sort()) {
      parts.push('```', readFileSync(join(dir, f), 'utf8').trim(), '```', '');
    }
  }
}
writeFileSync(out, `${parts.join('\n')}\n`, 'utf8');
console.log(`wrote ${out}: ${all.length} dependencies of ${closure.length} workspace packages`);
